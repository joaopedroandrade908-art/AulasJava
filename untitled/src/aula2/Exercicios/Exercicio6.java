package aula2.Exercicios;

public class Exercicio6 {
    public static void main(String[] args) {
        int num1 = 15;
        int num2 = 20;

        System.out.println("Valores: num1 = " + num1 + " e num2 = " + num2);
        System.out.println("num1 > num2: " + (num1 > num2));
        System.out.println("num1 < num2: " + (num1 < num2));
        System.out.println("num1 >= num2: " + (num1 >= num2));
        System.out.println("num1 <= num2: " + (num1 <= num2));
        System.out.println("num1 == num2: " + (num1 == num2));
        System.out.println("num1 != num2: " + (num1 != num2));
    }
}